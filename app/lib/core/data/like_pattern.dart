/// SQL `LIKE`/`ILIKE` 패턴에 사용자 입력을 끼워 넣을 때 쓰는 이스케이프.
///
/// PostgREST 의 `like`/`ilike` 는 값을 그대로 SQL 패턴으로 넘긴다. 사용자가 친
/// `%` 와 `_` 는 리터럴이어야 하는데 이스케이프하지 않으면 와일드카드로 해석된다
/// — 닉네임 중복 확인이 `a_ice` 로 `alice` 를 잡아 비어 있는 이름을 "이미 사용
/// 중"으로 막던 버그가 이것이었다 (2026-08-27 리뷰, [NicknameMatch]).
///
/// **`*` 는 막지 못한다.** PostgREST 가 패턴을 파싱하며 `*` 를 `%` 로 바꾸는데,
/// 앞에 역슬래시를 붙여도 `\%`(리터럴 `%`)가 되어버려 뜻이 또 달라진다. 그래서
/// `*` 가 들어오면 필터가 의도보다 넓게 걸린다 — 넓게 거는 것은 안전한 방향이라
/// (없는 것을 만들어내지 않는다) 호출부가 Dart 에서 최종 판정을 하면 결과는 옳다.
abstract final class LikePattern {
  /// 역슬래시를 **먼저** 바꾼다. 나중에 하면 방금 넣은 이스케이프를 다시
  /// 이스케이프한다.
  static String escape(String value) => value
      .replaceAll(r'\', r'\\')
      .replaceAll('%', r'\%')
      .replaceAll('_', r'\_');
}
